        let globalSlideIndex = 0;

        function startMasterSyncSlide() {
            setInterval(() => {
                globalSlideIndex++;
                const wrappers = document.querySelectorAll('.sync-wrapper');
                
                wrappers.forEach((wrapper, i) => {
                    const p = products[i];
                    if (!p || p.imgs.length <= 1) return;

                    const totalImgs = p.imgs.length;
                    const localIndex = globalSlideIndex % totalImgs;
                    
                    const movePercentage = localIndex * (100 / totalImgs);
                    wrapper.style.transform = `translateX(-${movePercentage}%)`;
                    
                    const container = wrapper.closest('.img-container');
                    const dots = container.querySelectorAll('.dot');
                    dots.forEach((d, idx) => {
                        if(idx === localIndex) {
                            d.classList.add('bg-[#c5a367]', 'scale-125');
                            d.classList.remove('bg-white/30');
                        } else {
                            d.classList.remove('bg-[#c5a367]', 'scale-125');
                            d.classList.add('bg-white/30');
                        }
                    });
                });
            }, 3500);
        }


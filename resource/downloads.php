    <script>
        function openFullView(pdfUrl, title) {
            const modal = new bootstrap.Modal(document.getElementById('pdfModal'));
            
            let finalUrl = pdfUrl + '#view=FitH';
            if (window.innerWidth < 992) {
                finalUrl = 'https://docs.google.com/viewer?url=https://theyyampattilgcc.com/' + pdfUrl + '&embedded=true';
            }

            document.getElementById('modalIframe').src = finalUrl;
            document.getElementById('modalTitle').innerText = title;
            document.getElementById('modalDownloadBtn').href = pdfUrl;
            modal.show();
        }
        
        document.getElementById('pdfModal').addEventListener('hidden.bs.modal', function () {
            document.getElementById('modalIframe').src = '';
        });

                document.querySelectorAll('.faq-answer').forEach(a => a.style.display = 'none');
                document.querySelectorAll('.faq-question span').forEach(s => s.innerText = '+');
                
                if (!isOpen) {
                    answer.style.display = 'block';
                    item.querySelector('span').innerText = '-';
                }
            });
        });
